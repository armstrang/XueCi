#!/usr/bin/env python3
"""Writes mobile/lib/app/talk/sound.g.dart: every common character (GB2312 + the app's words) mapped to one
representative character of its toneless syllable, so the talk engine can match a phrase whatever homophone the
phone's recognizer wrote (道歉 / 到歉). Needs pypinyin (MIT): python3 mobile/tool/make_talk.py <python-pinyin dir>."""
import sys, os, json, glob
sys.path.insert(0, sys.argv[1] if len(sys.argv) > 1 else '')
from pypinyin import lazy_pinyin

root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
chars = set()
for hi in range(0xB0, 0xF8):
    for lo in range(0xA1, 0xFF):
        try: c = bytes([hi, lo]).decode('gb2312')
        except UnicodeDecodeError: continue
        chars.add(c)
def take(s):
    for c in s:
        if '一' <= c <= '鿿': chars.add(c)
for f in [os.path.join(root, 'content/vocab.json')] + glob.glob(os.path.join(root, 'content/bct/*.txt')):
    take(open(f, encoding='utf8').read())
take(open(os.path.join(root, 'mobile/lib/app/talk/lexicon.dart'), encoding='utf8').read())
syl = {}
for c in chars:
    p = lazy_pinyin(c)[0]
    if not p.isalpha(): continue
    syl[c] = p.replace('ü', 'v')
rep = {}
for c, p in syl.items():
    if p not in rep or ord(c) < ord(rep[p]): rep[p] = c
pairs = sorted((c, rep[p]) for c, p in syl.items() if rep[p] != c)
src = ''.join(a for a, _ in pairs); dst = ''.join(b for _, b in pairs)
words = set()
for l in open(os.path.join(root, 'content/vocab.json'), encoding='utf8'):
    l = l.strip().rstrip(',')
    if not l.startswith('{'): continue
    try: o = json.loads(l)
    except Exception: continue
    if o.get('l', 9) <= 6 and len(o.get('h', '')) == 2: words.add(o['h'])
for f in glob.glob(os.path.join(root, 'content/bct/words*.txt')):
    for l in open(f, encoding='utf8'):
        h = l.split('|')[0].strip().split()[0] if l.strip() and not l.startswith('#') else ''
        if len(h) == 2 and all('\u4e00' <= c <= '\u9fff' for c in h): words.add(h)
out = os.path.join(root, 'mobile/lib/app/talk/sound.g.dart')
with open(out, 'w', encoding='utf8') as f:
    f.write('// Generated by mobile/tool/make_talk.py from pypinyin readings. Do not edit.\n')
    f.write('// Each character of _from is written as the character at the same place in _to (same toneless syllable).\n\n')
    f.write("const soundFrom = '%s';\n" % src)
    f.write("const soundTo = '%s';\n" % dst)
    f.write('\n// two-character words of HSK 1-6 and BCT, one after another: a homophone slip does not break a real word\n')
    f.write("const soundWords = '%s';\n" % ''.join(sorted(words)))
print(f'{len(syl)} characters, {len(rep)} syllables, {len(pairs)} mapped -> {out}')
