/// The cues of the talk engine: for each act (what the seller does in a sentence), regular expressions over hanzi.
/// They are matched twice: on the words as heard, and on the words written as one character per toneless syllable
/// (sound.g.dart), so a homophone the recognizer wrote (到歉 for 道歉) still matches, at a lower confidence.
/// A cue marked [exact] is only matched as written (short words whose syllables are too common: 好的, 行).
library;

class Cue {
  final String act;
  final String re;

  /// confidence when matched as written
  final double w;

  /// match the words as written only
  final bool exact;

  /// the cue itself says the act is not done (发不了, 退不了)
  final bool neg;
  const Cue(this.act, this.re, {this.w = 1, this.exact = false, this.neg = false});
}

