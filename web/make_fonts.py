"""Make the fonts that ship inside the Android app (no Google Fonts download at run time).

    python3 web/make_fonts.py [SOURCE_DIR]

SOURCE_DIR (default web/fonts/src, not committed) must hold the original variable fonts (all SIL OFL 1.1):
  PlusJakartaSans[wght].ttf, PlusJakartaSans-Italic[wght].ttf, OFL-PlusJakartaSans.txt
        from https://github.com/tokotype/PlusJakartaSans  (fonts/variable/, OFL.txt)
  NotoSansSC[wght].ttf, NotoSerifSC[wght].ttf, NotoSansThai[wdth,wght].ttf  + OFL-<Family>.txt
        from https://github.com/google/fonts  (ofl/notosanssc, ofl/notoserifsc, ofl/notosansthai)
  e.g.  git clone --depth 1 --filter=blob:none --sparse https://github.com/google/fonts.git gf
        git -C gf sparse-checkout set ofl/notosanssc ofl/notoserifsc ofl/notosansthai

The Chinese fonts are cut down to the characters the app actually shows (word list, example sentences,
interface text), which keeps them small. Re-run this after adding words: web/build.py warns when the page
uses a Chinese character that the bundled fonts don't have.

Writes app/src/main/assets/fonts/*.woff + licence files, web/fonts/fonts.css and web/fonts/charset.txt.
"""
import glob
import json
import os
import shutil
import sys

from fontTools import subset
from fontTools.ttLib import TTFont
from fontTools.varLib import instancer

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, 'web', 'fonts', 'src')
OUT = os.path.join(ROOT, 'app', 'src', 'main', 'assets', 'fonts')
CSS = os.path.join(ROOT, 'web', 'fonts', 'fonts.css')
CHARSET = os.path.join(ROOT, 'web', 'fonts', 'charset.txt')


def is_han(c):
    o = ord(c)
    return 0x3400 <= o <= 0x9FFF or 0xF900 <= o <= 0xFAFF or 0x20000 <= o <= 0x2FFFF


def app_text():
    """Every character the page can show: the word data plus all source files."""
    parts = []
    for p in glob.glob(os.path.join(ROOT, 'web', 'src', '**', '*'), recursive=True):
        if not os.path.isfile(p):
            continue
        with open(p, encoding='utf8') as f:
            parts.append(f.read())
    with open(os.path.join(ROOT, 'web', 'data', 'vocab.json'), encoding='utf8') as f:
        parts.append(json.dumps(json.load(f), ensure_ascii=False))
    return ''.join(parts)


def rng(a, b):
    return list(range(a, b + 1))


LATIN = rng(0x20, 0x7E) + rng(0xA0, 0x24F) + rng(0x1E00, 0x1EFF) + rng(0x2000, 0x206F) + [0x20AB, 0x20AC] + rng(0x2190, 0x21FF) + [0x2248, 0x2212]
THAI = rng(0x20, 0x40) + rng(0x0E00, 0x0E7F) + rng(0x2000, 0x206F)


def build(src, out, unicodes, axes):
    font = TTFont(src)
    opts = subset.Options()
    opts.hinting = False
    opts.desubroutinize = True
    opts.layout_features = ['*']
    opts.name_IDs = ['*']
    opts.notdef_outline = True
    opts.flavor = 'woff'          # zlib-compressed; Chromium/WebView read it natively
    sub = subset.Subsetter(opts)
    sub.populate(unicodes=unicodes)
    sub.subset(font)
    if 'fvar' in font:
        font = instancer.instantiateVariableFont(font, axes, updateFontNames=False)
    font.flavor = 'woff'
    font.save(os.path.join(OUT, out))
    return os.path.getsize(os.path.join(OUT, out))


def main():
    os.makedirs(OUT, exist_ok=True)
    for f in glob.glob(os.path.join(OUT, '*.woff')):
        os.remove(f)
    text = app_text()
    han = sorted({c for c in text if is_han(c)})
    cjk = [ord(c) for c in han] + rng(0x20, 0x7E) + rng(0x3000, 0x303F) + rng(0xFF00, 0xFFEF) + rng(0x2010, 0x2027)
    S = lambda name: os.path.join(SRC, name)
    jobs = [
        # file, source, unicodes, axes, @font-face family, weight, style
        ('pjs.woff', 'PlusJakartaSans[wght].ttf', LATIN, {'wght': (400, 800)}, 'Plus Jakarta Sans', '400 800', 'normal'),
        ('pjs-italic.woff', 'PlusJakartaSans-Italic[wght].ttf', LATIN, {'wght': (500, 600)}, 'Plus Jakarta Sans', '500 600', 'italic'),
        ('thai.woff', 'NotoSansThai[wdth,wght].ttf', THAI, {'wdth': 100, 'wght': (400, 800)}, 'Noto Sans Thai', '400 800', 'normal'),
        ('sans-sc-400.woff', 'NotoSansSC[wght].ttf', cjk, {'wght': 400}, 'Noto Sans SC', '400', 'normal'),
        ('sans-sc-700.woff', 'NotoSansSC[wght].ttf', cjk, {'wght': 700}, 'Noto Sans SC', '700', 'normal'),
        ('serif-sc-700.woff', 'NotoSerifSC[wght].ttf', cjk, {'wght': 700}, 'Noto Serif SC', '700', 'normal'),
        ('serif-sc-900.woff', 'NotoSerifSC[wght].ttf', cjk, {'wght': 900}, 'Noto Serif SC', '900', 'normal'),
    ]
    css = ['/* generated by web/make_fonts.py; fonts are SIL OFL 1.1, licences in assets/fonts/ */']
    total = 0
    for out, src, uni, axes, fam, wt, style in jobs:
        size = build(S(src), out, uni, axes)
        total += size
        print(f'{out:20s} {size / 1024:8.0f} KB')
        css.append(f'@font-face{{font-family:"{fam}";src:url("fonts/{out}") format("woff");font-weight:{wt};font-style:{style};font-display:block}}')
    for lic in glob.glob(os.path.join(SRC, 'OFL-*.txt')):
        shutil.copy(lic, os.path.join(OUT, os.path.basename(lic)))
    os.makedirs(os.path.dirname(CSS), exist_ok=True)
    with open(CSS, 'w', encoding='utf8') as f:
        f.write('\n'.join(css) + '\n')
    with open(CHARSET, 'w', encoding='utf8') as f:
        f.write(''.join(han) + '\n')
    print(f'total {total / 1024 / 1024:.2f} MB, {len(han)} Chinese characters')


main()
